// no-token: gh -- reads renovate.json and the tracked YAML and Markdown files as text and runs `git ls-files` in this checkout; nothing reaches GitHub.
/**
 * #5222 (epic #5153, item 1): every `uses: a11ign/...@<sha>` pin in the tree is READ BY A RENOVATE MANAGER OR EXCLUDED BY NAME, with a reason.
 * A pin that neither covers is bumped by hand, which is the work the epic removes, and nothing else would notice it being missed.
 *
 * What is pinned, and the wrong answer each guards against:
 *   1. THE POPULATION COMES FROM THE TREE: every tracked YAML and Markdown line that pins an a11ign repository by a full commit sha is a site.
 *      A floor of two (the consumer gate and the README) says the derivation found them, so an empty scan cannot pass as "all read".
 *   2. A SITE IS READ OR EXCLUDED: a site with neither is an offender. The positive control is a fixture pin that no entry reads.
 *   3. AN EXCLUSION IS NAMED AND IN FORCE: `ignorePaths` in renovate.json is exactly the reasoned table below, and each path still holds a
 *      pin. A dead exclusion is a file nobody reads, which is the same silence as a missing manager.
 *   4. RENOVATE RUNS ONLY ITS CUSTOM MANAGERS: the shared preset turns on every built-in manager and automerges, so `github-actions` would
 *      open a second pull request for each `uses:` line Dependabot already moves (`.github/dependabot.yml`, #3775).
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { sandboxGitEnv } from "./git-env.ts";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const FULL_SHA_LENGTH = 40;
const MIN_REASON_LENGTH = 40;
const PIN_LINE = /\buses:\s*(a11ign\/[^\s@]+)@([0-9a-f]{40})\b/;
const SCANNED_FILE = /\.(ya?ml|md)$/;

type TrackedFile = { path: string; text: string };
type Site = { path: string; line: number; text: string; repository: string; sha: string };
type CustomManager = { fileMatch?: string[]; matchStrings?: string[] };
type RenovateConfig = {
  extends: string[];
  enabled: boolean;
  enabledManagers: string[];
  ignorePaths: string[];
  customManagers?: CustomManager[];
};

/**
 * Each file Renovate leaves alone, and why. A pin in one of these is covered by its owner, not by a manager here.
 */
const EXCLUDED_BY_NAME = {
  ".github/workflows/consumer-gate.yml":
    "GENERATED by scripts/generate-consumer-gate.ts, which holds the pin at four sites; consumer-gate-pin.yml repairs it (#4331), and dependabot.yml ignores it (#3804). Two movers would fight.",
  ".github/workflows/release.yml":
    "calls a11ign/toolchain's reusable release workflow at a full sha; Dependabot's github-actions ecosystem reads and moves it (dependabot.yml, #3775). A second manager opens the same bump twice.",
  "README.md":
    "a docs pin, written by docs-pin-write on each release (#5224). A Renovate bump would race that writer on the same line and break the pin currency guard.",
  "docs/github-action.md":
    "a docs pin, written by docs-pin-write on each release (#5224), in the same set as README.md (docs-release-pin-currency.ts GUARDED_DOC).",
  "docs/try-it.md":
    "a docs pin, written by docs-pin-write on each release (#5224), in the same set as README.md (docs-release-pin-currency.ts GUARDED_DOC).",
  "examples/nightly-workflow.yml":
    "a consumer example pinned to release 0.5.3, which its own comment names. Nothing moves it, and a bump would leave that comment naming the wrong release. Open: whether an example should follow the release.",
  "scripts/outsider/outsider-job.yml":
    "GENERATED from README's Quickstart by scripts/outsider/generate.ts, and rewritten with the docs by docs-pin-write (#5291). Its pin is the release writer's.",
};

function pinSites(files: TrackedFile[]): Site[] {
  return files.flatMap(({ path, text }) =>
    text.split("\n").flatMap((line, index) => {
      const match = PIN_LINE.exec(line);
      return match ? [{ path, line: index + 1, text: line, repository: match[1], sha: match[2] }] : [];
    }),
  );
}

function readsSite(manager: CustomManager, site: Site): boolean {
  const fileMatches = (manager.fileMatch ?? []).some((pattern) => new RegExp(pattern).test(site.path));
  const lineMatches = (manager.matchStrings ?? []).some((pattern) => new RegExp(pattern).test(site.text));
  return fileMatches && lineMatches;
}

function unreadPins(sites: Site[], config: RenovateConfig): Site[] {
  const managers = config.customManagers ?? [];
  return sites.filter((site) => !config.ignorePaths.includes(site.path) && !managers.some((manager) => readsSite(manager, site)));
}

function trackedFiles(): TrackedFile[] {
  const listed = execFileSync("git", ["ls-files"], { cwd: REPO_ROOT, env: sandboxGitEnv(), encoding: "utf8" }).split("\n");
  return listed
    .filter((path) => SCANNED_FILE.test(path))
    .map((path) => ({ path, text: readFileSync(resolve(REPO_ROOT, path), "utf8") }));
}

function renovateConfig(root = REPO_ROOT): RenovateConfig {
  return JSON.parse(readFileSync(resolve(root, "renovate.json"), "utf8"));
}

test("every a11ign pin in the tree is read by a custom manager or excluded by name", () => {
  const sites = pinSites(trackedFiles());
  assert.ok(sites.length >= 2, `the scan found ${sites.length} a11ign pins; the consumer gate and the README alone are two`);
  assert.ok(sites.some((site) => site.path === ".github/workflows/consumer-gate.yml"), "the consumer gate's pin is in the population");
  assert.deepEqual(unreadPins(sites, renovateConfig()).map((site) => `${site.path}:${site.line}`), []);
});

test("a pin no manager reads is an offender, and a manager that reads it clears it", () => {
  const fixture = [{ path: ".github/workflows/new.yml", text: `      - uses: a11ign/toolchain/.github/workflows/x.yml@${"a".repeat(FULL_SHA_LENGTH)}` }];
  const sites = pinSites(fixture);
  assert.equal(sites.length, 1, "the fixture pin is in the population");
  assert.equal(unreadPins(sites, renovateConfig()).length, 1, "no entry reads the fixture, so it is an offender");
  const reader = {
    customType: "regex",
    fileMatch: ["^\\.github/workflows/new\\.yml$"],
    matchStrings: ["uses: (?<depName>a11ign/[^@]+)@(?<currentDigest>[0-9a-f]{40})"],
  };
  assert.deepEqual(unreadPins(sites, { ...renovateConfig(), customManagers: [reader] }), []);
});

test("each exclusion is named with a reason, and still holds a pin", () => {
  const config = renovateConfig();
  const sites = pinSites(trackedFiles());
  assert.deepEqual([...config.ignorePaths].sort(), Object.keys(EXCLUDED_BY_NAME).sort());
  for (const [path, reason] of Object.entries(EXCLUDED_BY_NAME)) {
    assert.ok(reason.length > MIN_REASON_LENGTH, `${path} needs a reason, not a name`);
    assert.ok(sites.some((site) => site.path === path), `${path} is excluded but holds no a11ign pin: a dead exclusion`);
  }
});

test("Renovate is enrolled in the shared preset and runs only its custom managers", () => {
  const config = renovateConfig();
  assert.equal(config.enabled, true);
  assert.ok(config.extends.includes("local>a11ign/.github"));
  assert.deepEqual(config.enabledManagers, ["custom.regex"]);
});
